"""What pads KiCad's own footprints carry — shipped as data, read hermetically.

**The gap this closes.** `package = "Lib:Footprint"` makes Ohm emit a pad-LESS
stub: the geometry comes from the user's installed library at layout time, and
only the pad id travels, in the netlist. So `pin SHIELD: pad=11` is correct only
if the library on that machine still calls it 11 — and KiCad renames pads between
releases. KiCad 10 normalised shield and shell pads to `"SH"` across **163**
footprints (`0`, `S1`, `6`, `5`, `11`, `9` all became `SH`), which leaves the
shield silently unconnected on every board that names the old id. Ohm could not
see it, because Ohm never reads a footprint: S003 proves the pin->pad map is
TOTAL, and nothing proved the pads it names exist.

**Why data rather than a lookup.** Compilation is hermetic (N1) — no disk
outside the package, no network, no clock — so "does this footprint have a pad
called 11?" cannot be answered by reading the user's KiCad during `ohm check`.
It is answered from a table generated by `tools/gen_fpdata.py` against real
installed libraries and shipped with Ohm, which is the same shape as ADR-014's
pinout provenance: acquire at author time, freeze, check against the frozen
copy. `ohm verify-footprints` is the author-time half that re-reads the real
library, exactly as `ohm verify-pinouts` does for symbols.

**Honest limits.**

- The table covers the KiCad majors it was generated against (`KICAD_MAJORS`).
  KiCad 7 is not among them — no official container image exists for it — so a
  KiCad 7 target is *unchecked*, not *checked and clean*. Callers must treat an
  unknown major as "abstain", never as "fine".
- A footprint that is not in the table is unknown, not absent. Users reference
  their own and third-party libraries, and guessing about those is how a checker
  earns the right to be ignored. `pads()` returns None and the caller abstains.
- Renames are derived only in the old->new direction, and only where exactly one
  pad appeared. That covers every real case, including the ten footprints where
  two shield pads MERGE into one `SH`. The reverse is genuinely ambiguous after a
  merge and is deliberately not offered.
"""

from __future__ import annotations

import gzip
import json
from functools import lru_cache
from pathlib import Path

_DATA = Path(__file__).parent / "pads.json.gz"


@lru_cache(maxsize=1)
def _table() -> dict:
    """The shipped table, decoded once per process."""
    with gzip.open(_DATA, "rt", encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=1)
def kicad_majors() -> tuple[str, ...]:
    """The KiCad majors this table can answer for, oldest first."""
    return tuple(_table()["kicad_majors"])


def _decode(encoded: int | list[str]) -> frozenset[str]:
    """`N` means pads 1..N; a list is the pad ids verbatim."""
    if isinstance(encoded, int):
        return frozenset(str(i) for i in range(1, encoded + 1))
    return frozenset(encoded)


def known(footprint: str) -> bool:
    """Is this a footprint the table has anything to say about?"""
    return footprint in _table()["base"]


def present_in(footprint: str, major: str) -> bool:
    """Does `major`'s library ship this footprint at all?

    False for a footprint KiCad removed — referencing one is a real defect,
    distinct from naming a pad it does not have.
    """
    table = _table()
    if footprint not in table["base"] or major not in table["kicad_majors"]:
        return False
    return footprint not in table["absent"].get(major, [])


def pads(footprint: str, major: str) -> frozenset[str] | None:
    """The pad ids `footprint` carries in KiCad `major`.

    None means "no answer" — an unknown footprint, an unknown major, or a
    footprint that version does not ship. A caller must abstain on None rather
    than treat it as an empty set, which would report every pad as missing.
    """
    table = _table()
    if footprint not in table["base"] or major not in table["kicad_majors"]:
        return None
    if not present_in(footprint, major):
        return None
    override = table["overrides"].get(footprint, {}).get(major)
    return _decode(override if override is not None else table["base"][footprint])


def renamed_to(footprint: str, pad: str, major: str) -> str | None:
    """What `pad` became in KiCad `major`, if it was renamed. Else None.

    e.g. renamed_to("Connector_Card:microSD_HC_Hirose_DM3AT-SF-PEJM5", "11", "10")
    -> "SH".
    """
    return _table()["renames"].get(footprint, {}).get(major, {}).get(pad)


def majors_lacking(footprint: str, pad: str) -> tuple[str, ...]:
    """Every known major whose version of `footprint` has no such pad.

    This is what a check uses when the user has NOT named a target KiCad: the
    honest report is then "this pad does not exist in these versions", naming
    them, rather than picking one and pretending it is the only one.
    """
    out = []
    for major in kicad_majors():
        have = pads(footprint, major)
        if have is not None and pad not in have:
            out.append(major)
    return tuple(out)


def absence(footprint: str, major: str) -> str | None:
    """WHY `footprint` is missing from KiCad `major` — "added_later", "removed",
    "gap", or None if it is present (or the footprint/major is unknown).

    The distinction is not pedantry, it is the difference between two opposite
    instructions to the author. A footprint KiCad REMOVED means "this part is
    gone, name its replacement". A footprint KiCad had not ADDED YET means "this
    part is fine, your KiCad is older than it" — and the fix is to upgrade KiCad
    or pick a footprint that predates it, not to go hunting for a removal that
    never happened.

    Both directions are real and neither is rare. Against the shipped table:
    **728** footprints exist in KiCad 8, 9 and 10 but not in 7 (added since), and
    **379** that KiCad 7 shipped are gone by 10 (removed). S012 called both "no
    longer ships" until KiCad 7 data existed to make the difference visible — and
    the first thing that data found was Ohm's own standard library naming a
    connector footprint added after KiCad 7, on the DEFAULT target.

    "gap" is the honest answer for a footprint present on both sides of `major`
    but not in it. Nothing in the shipped table exhibits it today; it is here so
    that a future removal-and-reinstatement is reported as the odd thing it is
    rather than being forced into one of the two clean stories.
    """
    if not known(footprint) or major not in kicad_majors():
        return None
    if present_in(footprint, major):
        return None
    live = [m for m in kicad_majors() if present_in(footprint, m)]
    if not live:                       # known to the table, present in no major
        return "removed"               # cannot arise from _merge, kept total
    order = {m: i for i, m in enumerate(kicad_majors())}
    here = order[major]
    if here < min(order[m] for m in live):
        return "added_later"
    if here > max(order[m] for m in live):
        return "removed"
    return "gap"


def summarise(footprint: str, major: str, limit: int = 12) -> str:
    """A short, readable rendering of a footprint's pads, for a diagnostic."""
    have = pads(footprint, major)
    if have is None:
        return "(unknown)"
    ordered = sorted(have, key=lambda p: (len(p), p))
    shown = ", ".join(ordered[:limit])
    return shown if len(ordered) <= limit else f"{shown}, … ({len(ordered)} pads)"
