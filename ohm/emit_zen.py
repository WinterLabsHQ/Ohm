"""P7: .zen export — IR-LOW → Starlark using the universal Component() form.

Deterministic: nets in IR-LOW order (sorted), pins sorted by name, sanitized
variable names uniquified stably. Interop only — never a build dependency.
"""

from __future__ import annotations

import re

from ohm import ir

_IDENT = re.compile(r"[^A-Za-z0-9_]")


def _varname(net_name: str, taken: dict[str, str]) -> str:
    base = _IDENT.sub("_", net_name).upper() or "N"
    if base[0].isdigit():
        base = "N_" + base
    var, i = base, 1
    while var in taken and taken[var] != net_name:
        i += 1
        var = f"{base}_{i}"
    taken[var] = net_name
    return var


def emit_zen(low: ir.IRLow, source: str = "<string>") -> str:
    out = [f"# generated by ohm from {source}", ""]
    taken: dict[str, str] = {}
    net_var: dict[str, str] = {}
    for net in low.nets:
        var = _varname(net.name, taken)
        net_var[net.name] = var
        out.append(f'{var} = Net("{net.name}")')
    out.append("")
    pin_net: dict[str, list[tuple[str, str]]] = {}
    for net in low.nets:
        for node in net.nodes:
            pin_net.setdefault(node.part_ref, []).append((node.pin, net_var[net.name]))
    for part in low.parts:
        fp = part.package if isinstance(part.package, str) else ""
        prefix = "".join(c for c in part.designator if c.isalpha()) or "U"
        pins = ", ".join(f'"{pin}": {var}' for pin, var in sorted(pin_net.get(part.ref, [])))
        out.append(
            f'Component(name="{part.ref}", footprint="{fp}", prefix="{prefix}", '
            f"pins={{{pins}}})"
        )
    return "\n".join(out) + "\n"
